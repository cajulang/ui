// Writes cmd/assets.caju: the files of assets/ as Caju string constants, so the caju-ui command
// carries them (run it after changing anything in assets/: node tools/embed.mjs).
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const files = [["UI_JS", "ui.js"], ["WORKER_JS", "worker.js"], ["HOST_JS", "caju-host.mjs"]]

const quote = (s) => {
  let out = '"'
  for (const ch of s) {
    const c = ch.codePointAt(0)
    if (ch === '"') out += '\\"'
    else if (ch === "\\") out += "\\\\"
    else if (ch === "\n") out += "\\n"
    else if (ch === "\t") out += "\\t"
    else if (ch === "\r") out += "\\r"
    else if (c < 32) out += "\\x" + c.toString(16).padStart(2, "0")
    else out += ch
  }
  return out + '"'
}

let out = "# Generated by tools/embed.mjs from assets/: do not edit (edit assets/ and run it again).\n\n"
for (const [name, file] of files) {
  out += `# assets/${file}\nexport const ${name} = ${quote(readFileSync(join(root, "assets", file), "utf8"))}\n\n`
}
writeFileSync(join(root, "cmd", "assets.caju"), out)
console.log("cmd/assets.caju: " + files.map((f) => f[1]).join(", "))
